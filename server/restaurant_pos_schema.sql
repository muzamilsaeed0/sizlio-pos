BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ============================================================
-- RESTAURANTS
-- ============================================================
CREATE TABLE public.restaurants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(150) NOT NULL,
  owner_name VARCHAR(100),
  phone VARCHAR(30),
  email VARCHAR(150),
  city VARCHAR(100),
  address TEXT,
  plan VARCHAR(50) NOT NULL DEFAULT 'Basic',
  status VARCHAR(20) NOT NULL DEFAULT 'Active',
  expiry_date DATE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  logo_url VARCHAR(500),
  food_type VARCHAR(100) NOT NULL DEFAULT 'Fast Food',
  business_type VARCHAR(30) NOT NULL DEFAULT 'restaurant',

  -- POS / payment settings
  pos_settings JSONB NOT NULL DEFAULT '{}'::jsonb,
  raast_qr_string TEXT,

  -- Restaurant location / GPS lock
  latitude NUMERIC(10,7),
  longitude NUMERIC(10,7),
  gps_radius_meters NUMERIC(10,2) NOT NULL DEFAULT 100,

  -- Restaurant-level charge defaults
  delivery_charge NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (delivery_charge >= 0),
  dine_charge NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (dine_charge >= 0),
  card_charge NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (card_charge >= 0),
  bank_charge NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (bank_charge >= 0),

  -- FBR integration
  fbr_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  fbr_pos_registration_no VARCHAR(100),
  fbr_api_token TEXT,
  fbr_seller_ntn_cnic VARCHAR(100),
  fbr_seller_business_name VARCHAR(200),
  fbr_seller_province VARCHAR(100),
  fbr_seller_address TEXT,
  fbr_environment VARCHAR(20) NOT NULL DEFAULT 'sandbox'
    CHECK (fbr_environment IN ('sandbox','production'))
);

CREATE INDEX restaurants_status_idx ON public.restaurants(status);
CREATE INDEX restaurants_plan_idx ON public.restaurants(plan);

-- ============================================================
-- USERS
-- ============================================================
CREATE TABLE public.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL
    CHECK (role IN (
