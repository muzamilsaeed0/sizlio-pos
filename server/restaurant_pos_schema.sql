-- Payment ledger is append-only.
CREATE OR REPLACE FUNCTION public.prevent_payment_transaction_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION 'payment_transactions is append-only; use a new transaction row';
END;
$$;

CREATE TRIGGER payment_transactions_no_update
BEFORE UPDATE ON public.payment_transactions
FOR EACH ROW EXECUTE FUNCTION public.prevent_payment_transaction_mutation();

CREATE TRIGGER payment_transactions_no_delete
BEFORE DELETE ON public.payment_transactions
FOR EACH ROW EXECUTE FUNCTION public.prevent_payment_transaction_mutation();

