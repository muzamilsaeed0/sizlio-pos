  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  restaurant_id INTEGER REFERENCES public.restaurants(id) ON DELETE CASCADE,

  current_session TEXT,
  last_login_at TIMESTAMPTZ,
