-- ============================================================
-- ORDERS
-- ============================================================
CREATE TABLE public.orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  table_no INTEGER NOT NULL DEFAULT 0,
  local_number INTEGER,

  restaurant_id INTEGER NOT NULL
    REFERENCES public.restaurants(id) ON DELETE CASCADE,

  customer_name VARCHAR(100),

  status VARCHAR(30) NOT NULL DEFAULT 'pending'
    CHECK (status IN (
      'pending','placed','accepted','preparing','confirmed','ready',
      'served','payment_pending','ready_to_dispatch','ready_to_deliver',
      'out_for_delivery','delivered','paid','completed','cancelled'
    )),

  prep_minutes INTEGER CHECK (prep_minutes IS NULL OR prep_minutes > 0),

  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT NOW(),
  confirmed_at TIMESTAMP WITHOUT TIME ZONE,
  ready_at TIMESTAMP WITHOUT TIME ZONE,
  served_at TIMESTAMP WITHOUT TIME ZONE,
  delivered_at TIMESTAMP WITHOUT TIME ZONE,
  completed_at TIMESTAMP WITHOUT TIME ZONE,

  inventory_deducted_at TIMESTAMP WITHOUT TIME ZONE,

  order_source VARCHAR(20) NOT NULL DEFAULT 'MENU'
    CHECK (order_source IN ('MENU','WAITER','COUNTER','PHONE')),

  order_type VARCHAR(20) NOT NULL DEFAULT 'dine_in'
    CHECK (order_type IN ('dine_in','delivery','walk_in')),

  payment_timing VARCHAR(20) NOT NULL DEFAULT 'PAY_LATER'
    CHECK (payment_timing IN ('PAY_LATER','PAID_AT_ORDER','COD')),

  delivery_phone VARCHAR(30),
  delivery_address TEXT,

  payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid'
    CHECK (payment_status IN ('unpaid','paid')),

  payment_method VARCHAR(30),
  paid_amount NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (paid_amount >= 0),
  paid_at TIMESTAMP WITHOUT TIME ZONE,
  paid_by_user_id INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL,
  change_amount NUMERIC(12,2) NOT NULL DEFAULT 0
    CHECK (change_amount >= 0),

  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount_type VARCHAR(20) NOT NULL DEFAULT 'none',
  discount_value NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  gst_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
  gst_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax_percent NUMERIC(5,2) NOT NULL DEFAULT 0,
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,

  delivery_charge NUMERIC(12,2) NOT NULL DEFAULT 0,
  dine_charge NUMERIC(12,2) NOT NULL DEFAULT 0,
  card_charge NUMERIC(12,2) NOT NULL DEFAULT 0,
  bank_charge NUMERIC(12,2) NOT NULL DEFAULT 0,

  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,

  created_by_user_id INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL,
  delivery_rider_id INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL
);

