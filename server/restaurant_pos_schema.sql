  last_login_device TEXT
);

CREATE INDEX users_restaurant_idx ON public.users(restaurant_id);
CREATE INDEX users_role_idx ON public.users(restaurant_id, role);
CREATE INDEX users_active_idx ON public.users(restaurant_id, is_active);

