CREATE TABLE public.wholesale_products (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL
    REFERENCES public.restaurants(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  sku VARCHAR(100),
  unit VARCHAR(30) NOT NULL DEFAULT 'pcs',
  purchase_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (purchase_price >= 0),
  sale_price NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (sale_price >= 0),
  stock NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (stock >= 0),
  min_stock NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (min_stock >= 0),
  category VARCHAR(100),
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX wholesale_products_restaurant_idx
  ON public.wholesale_products(restaurant_id, active);

CREATE TABLE public.wholesale_invoices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  restaurant_id INTEGER NOT NULL
    REFERENCES public.restaurants(id) ON DELETE CASCADE,
  local_number INTEGER NOT NULL,
  customer_name VARCHAR(150) DEFAULT 'Walk-in',
  subtotal NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount NUMERIC(12,2) NOT NULL DEFAULT 0,
  tax NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL DEFAULT 0,
  paid NUMERIC(12,2) NOT NULL DEFAULT 0,
  payment_type VARCHAR(30) NOT NULL DEFAULT 'cash',
  status VARCHAR(30) NOT NULL DEFAULT 'completed',
  created_by INTEGER
    REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (restaurant_id, local_number)
);

CREATE INDEX wholesale_invoices_restaurant_idx
  ON public.wholesale_invoices(restaurant_id, created_at DESC);

CREATE TABLE public.wholesale_invoice_items (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id INTEGER NOT NULL
    REFERENCES public.wholesale_invoices(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL
    REFERENCES public.wholesale_products(id) ON DELETE RESTRICT,
  name VARCHAR(150) NOT NULL,
  qty NUMERIC(12,2) NOT NULL CHECK (qty > 0),
  unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
  line_total NUMERIC(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE INDEX wholesale_invoice_items_invoice_idx
  ON public.wholesale_invoice_items(invoice_id);

