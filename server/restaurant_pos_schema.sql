  response_payload JSONB,
  retry_count INTEGER NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
  last_error TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  submitted_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX fbr_invoices_restaurant_idx
  ON public.fbr_invoices(restaurant_id, status, created_at DESC);
CREATE INDEX fbr_invoices_order_idx
  ON public.fbr_invoices(restaurant_id, order_id);

